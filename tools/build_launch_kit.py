#!/usr/bin/env python3
"""Writes launch/SEO.md from the page sources, so the table can never drift from what the pages actually say.

    python3 tools/build_launch_kit.py

Social cards come from `node tools/build_social.mjs`; the redirect plan and captions are hand-written files in launch/.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TITLE_MAX, DESC_MAX, DESC_MIN = 60, 155, 70
HOST = "https://ganjinehofogh.ir"


def pages():
    for f in sorted((ROOT / "src" / "pages").glob("*.html")):
        if f.name.startswith("_") or f.name == "404.html":
            continue
        meta = dict(re.findall(r'(\w+)="([^"]*)"', f.read_text(encoding="utf-8").split("\n")[0]))
        if meta.get("noindex"):
            continue
        yield meta


def flag(n, low, high):
    return "⚠ short" if n < low else "⚠ long" if n > high else "ok"


def main():
    order = ["index", "project", "architecture", "residences", "compare", "lifestyle", "location", "gallery", "developer", "brochure", "contact", "privacy"]
    metas = sorted(pages(), key=lambda m: order.index(m["key"]) if m["key"] in order else 99)
    out = ["# SEO titles and descriptions", "",
           "Generated by `python3 tools/build_launch_kit.py` from the first line of each `src/pages/*.html`. Edit the page, rebuild, rerun.", "",
           f"Limits used: title ≤ {TITLE_MAX} characters, description {DESC_MIN}–{DESC_MAX}. Both languages have their own canonical URL and `hreflang` links.", ""]
    problems = 0
    for lang, title_key, desc_key, prefix in (("Persian", "title_fa", "desc_fa", ""), ("English", "title_en", "desc_en", "/en")):
        out += [f"## {lang}", "", "| URL | Title | chars | Description | chars | |", "|---|---|---|---|---|---|"]
        for m in metas:
            url = f"{HOST}{prefix}/" + ("" if m["key"] == "index" else m["key"] + ".html")
            t, d = m[title_key], m[desc_key]
            verdict = [v for v in (flag(len(t), 0, TITLE_MAX), flag(len(d), DESC_MIN, DESC_MAX)) if v != "ok"]
            problems += len(verdict)
            out.append(f"| `{url}` | {t} | {len(t)} | {d} | {len(d)} | {', '.join(verdict) or 'ok'} |")
        out.append("")
    out += ["## Not claimed", "",
            "No title or description states a price, a delivery date, a floor count or an orientation: none has been supplied. Areas are the supplied 143.25 / 150 / 166 / 162 m².", ""]
    (ROOT / "launch").mkdir(exist_ok=True)
    (ROOT / "launch" / "SEO.md").write_text("\n".join(out), encoding="utf-8")
    print(f"launch/SEO.md written ({len(metas)} pages x 2 languages, {problems} to review)")


if __name__ == "__main__":
    main()
